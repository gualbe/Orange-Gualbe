import sys
from AnyQt.QtCore import Qt, QRectF
from AnyQt.QtWidgets import QApplication, QGraphicsScene, QStyle
app = QApplication(sys.argv)
from Orange.widgets.utils.stickygraphicsview import (
    StickyGraphicsView, qgraphicsview_map_rect_from_scene, qrectf_to_inscribed_rect)
view = StickyGraphicsView(); scene = QGraphicsScene(view); view.setScene(scene)
scene.addRect(QRectF(0, 0, 300, 20)); scene.addRect(QRectF(0, 25, 300, 100)); scene.addRect(QRectF(0, 130, 300, 20))
view.setHeaderSceneRect(QRectF(0, 0, 300, 20)); view.setFooterSceneRect(QRectF(0, 130, 300, 20))
view.resize(310, 310); view.grab()
print("platform", app.platformName(), "style", app.style().objectName(), "dpr", view.devicePixelRatioF(), "logicalDpi", view.logicalDpiY())
print("transient scrollbar hint", view.style().styleHint(QStyle.SH_ScrollBar_Transient, None, view.verticalScrollBar()))
print("viewport rect", view.viewport().rect(), "vsb visible", view.verticalScrollBar().isVisibleTo(view), "range", view.verticalScrollBar().minimum(), view.verticalScrollBar().maximum())
print("hsb visible", view.horizontalScrollBar().isVisibleTo(view), "range", view.horizontalScrollBar().minimum(), view.horizontalScrollBar().maximum())
r = qgraphicsview_map_rect_from_scene(view, QRectF(0, 130, 300, 20)).boundingRect()
print("footer in viewport", r, "inscribed", qrectf_to_inscribed_rect(r))
print("header visible", view.headerView().isVisibleTo(view), "footer visible", view.footerView().isVisibleTo(view))
print("sceneRect", view.sceneRect(), "frame", view.frameWidth())
print("---- resize 310x100, scroll to bottom")
view.resize(310, 100); view.verticalScrollBar().setValue(0); view.grab()
vsb = view.verticalScrollBar(); vsb.setValue(vsb.maximum()); view.grab()
print("viewport rect", view.viewport().rect(), "vsb range", vsb.minimum(), vsb.maximum(), "value", vsb.value(), "hsb visible", view.horizontalScrollBar().isVisibleTo(view), "hsb range", view.horizontalScrollBar().maximum())
r = qgraphicsview_map_rect_from_scene(view, QRectF(0, 130, 300, 20)).boundingRect()
print("footer in viewport", r, "inscribed", qrectf_to_inscribed_rect(r))
print("mapToScene viewport bottom", view.mapToScene(0, view.viewport().height()).y(), "transform dy", view.viewportTransform().dy())
print("header visible", view.headerView().isVisibleTo(view), "footer visible", view.footerView().isVisibleTo(view))
print("PM_ScrollBarExtent", view.style().pixelMetric(QStyle.PM_ScrollBarExtent, None, vsb), "vsb width", vsb.width(), "hsb height", view.horizontalScrollBar().height(), "hsb sizeHint", view.horizontalScrollBar().sizeHint().height())
view.show(); app.processEvents(); vsb.setValue(vsb.maximum()); app.processEvents()
print("after show: viewport", view.viewport().rect(), "vsb max", vsb.maximum(), "footer visible", view.footerView().isVisibleTo(view))
